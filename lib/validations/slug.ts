import { z } from "zod";

/**
 * slug ใช้ร่วมกันทุกโมเดลที่มี URL เป็นของตัวเอง (News, Category, Tag, …)
 *
 * ตั้งเองเสมอ — **ไม่ auto-gen จากชื่อ** เพราะชื่อเป็นภาษาไทย แปลงตรง ๆ แล้วได้ string ว่าง
 * (slug ที่ต้องการคือคำแปลอังกฤษที่คนเลือกเอง เช่น "ข่าวประชาสัมพันธ์" → "announcements"
 *  ซึ่งไม่มีอัลกอริทึมไหนทำให้ได้ — ตัดสินใจ 2026-07-17)
 *
 * ห้ามขึ้น/ลงท้ายด้วย "-" และห้าม "--" ติดกัน
 */
export const slugSchema = z
  .string()
  .min(1, "กรุณากรอก slug")
  .max(100, "slug ยาวเกินไป (ไม่เกิน 100 ตัวอักษร)")
  .regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, "slug ใช้ได้เฉพาะ a-z, 0-9 และ - (เช่น wai-kru-2569)");
